#!/usr/bin/env bash
set -Eeuo pipefail

# Initialize the reusable GEDA -> QVI -> LE/OOR vLEI fixture for the human GL1
# smart-contract guide.
#
# This script intentionally hides the repetitive KLI issuance mechanics so the
# operator can focus on the GL1 integration increment: admin allowlists, CCID
# registry state, oracle-posted evidence, minting, approvals, and wUSDC
# transfers.

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
if [[ -n "${DEMO_ENV:-}" ]]; then
  # shellcheck disable=SC1090
  source "$DEMO_ENV"
fi
COMPLY_DIR="$(cd "${SCRIPT_DIR}/../.." && pwd)"
ORACLE_DIR="${ORACLE_DIR:-}"

STACK_RUN_ID="${STACK_RUN_ID:-local-gl1-stack}"
STACK_RUN_DIR="${STACK_RUN_DIR:-${COMPLY_DIR}/runs/${STACK_RUN_ID}}"
STACK_ENV="${STACK_ENV:-${STACK_RUN_DIR}/stack.env}"

RUN_ID="${RUN_ID:-local-gl1-fixture-$(date +%Y%m%d-%H%M%S)}"
RUN_DIR="${RUN_DIR:-${COMPLY_DIR}/runs/${RUN_ID}}"
KERI_BASE="${KERI_BASE:-${RUN_ID}}"
ACTORS_ENV="${ACTORS_ENV:-${RUN_DIR}/actors.env}"
ACTORS_JSON="${ACTORS_JSON:-${RUN_DIR}/actors.json}"
LATEST_FIXTURE_ENV="${LATEST_FIXTURE_ENV:-${COMPLY_DIR}/runs/latest-fixture.env}"
FIXTURE_RUN_ID="$RUN_ID"
FIXTURE_RUN_DIR="$RUN_DIR"
FIXTURE_KERI_BASE="$KERI_BASE"
FIXTURE_ACTORS_ENV="$ACTORS_ENV"
FIXTURE_ACTORS_JSON="$ACTORS_JSON"

THROUGH="oracle-posted"

usage() {
  cat <<'USAGE'
Usage:
  scripts/dev/init-local-vlei-fixture.sh [--through source-chain|oracle-posted]

Default:
  --through oracle-posted

Stages:
  source-chain   Create GEDA, QVI, originator/beneficiary LE and OOR AIDs,
                 resolve OOBIs, create registries, and issue/admit the vLEI
                 source chain.
  oracle-posted  Do source-chain, start/reuse vlei-oracle, issue GL1 wallet
                 attestations, Grant them to the oracle, POST CESR Ethereum
                 signatures, and wait for on-chain oracle posts.

The script expects the base stack to exist at runs/local-gl1-stack/stack.env.
If it is missing, the script starts it first.

After success:
  source runs/latest-fixture.env
USAGE
}

while [[ $# -gt 0 ]]; do
  case "$1" in
    --through)
      THROUGH="${2:-}"
      shift 2
      ;;
    -h|--help)
      usage
      exit 0
      ;;
    *)
      usage >&2
      exit 2
      ;;
  esac
done

case "$THROUGH" in
  source-chain|oracle-posted) ;;
  *)
    printf 'Invalid --through value: %s\n' "$THROUGH" >&2
    usage >&2
    exit 2
    ;;
esac

: "${ORACLE_DIR:?Source the clean-checkout demo.env to set ORACLE_DIR}"

printf 'Ensuring detached local stack is running from %s\n' "$STACK_ENV"
RUN_ID="$STACK_RUN_ID" \
  RUN_DIR="$STACK_RUN_DIR" \
  STACK_ENV="$STACK_ENV" \
  "${COMPLY_DIR}/scripts/dev/start-local-gl1-stack.sh" start

# shellcheck disable=SC1090
source "$STACK_ENV"

RUN_ID="$FIXTURE_RUN_ID"
RUN_DIR="$FIXTURE_RUN_DIR"
KERI_BASE="$FIXTURE_KERI_BASE"
ACTORS_ENV="$FIXTURE_ACTORS_ENV"
ACTORS_JSON="$FIXTURE_ACTORS_JSON"

mkdir -p "$RUN_DIR" "$(dirname "$LATEST_FIXTURE_ENV")"

export RUN_ID
export RUN_DIR
export KERI_BASE
export ACTORS_ENV
export ACTORS_JSON
export CONTRACTS_JSON
export RPC_URL
export CHAIN_ID
export ADMIN_PK
export ORACLE_URL
export ORACLE_HTTP_PORT
export VLEI_SCHEMA_PORT
export E2E_STOP_AFTER="$THROUGH"
export KEEP_SERVICES=1

"${ORACLE_DIR}/scripts/e2e/gl1-wallet-transfer-e2e.sh"

if [[ "$THROUGH" == "oracle-posted" ]]; then
  # shellcheck disable=SC1090
  source "$ACTORS_ENV"
  RUN_ID="$STACK_RUN_ID" \
    RUN_DIR="$STACK_RUN_DIR" \
    STACK_ENV="$STACK_ENV" \
    KERI_BASE="$FIXTURE_KERI_BASE" \
    GEDA_AID="$GEDA_AID" \
    "${COMPLY_DIR}/scripts/dev/start-local-gl1-stack.sh" oracle
fi

cat >"$LATEST_FIXTURE_ENV" <<ENV
# Generated by scripts/dev/init-local-vlei-fixture.sh.
source '${STACK_ENV}'
source '${ACTORS_ENV}'
ENV

printf '\nFixture initialized through: %s\n' "$THROUGH"
printf 'Actor exports: %s\n' "$ACTORS_ENV"
printf 'Actor JSON:    %s\n' "$ACTORS_JSON"
printf 'Load both stack and actor exports with:\n'
printf '  source %s\n' "$LATEST_FIXTURE_ENV"
